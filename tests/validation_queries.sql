USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_DW;

-- Expected raw counts: customers 5, products 5, orders 6, order_items 10.
SELECT COUNT(*) AS CUSTOMER_COUNT FROM RAW.CUSTOMERS;
SELECT COUNT(*) AS PRODUCT_COUNT FROM RAW.PRODUCTS;
SELECT COUNT(*) AS ORDER_COUNT FROM RAW.ORDERS;
SELECT COUNT(*) AS ORDER_ITEM_COUNT FROM RAW.ORDER_ITEMS;

-- Expected gross order-item value for supplied sample data: 27,390.00.
SELECT SUM(QUANTITY * UNIT_PRICE) AS SAMPLE_GROSS_REVENUE FROM RAW.ORDER_ITEMS;

-- Expected: no rows returned.
SELECT ORDER_ITEM_ID FROM STAGING.V_ORDER_ITEMS I
LEFT JOIN STAGING.V_ORDERS O ON I.ORDER_ID=O.ORDER_ID
LEFT JOIN STAGING.V_PRODUCTS P ON I.PRODUCT_ID=P.PRODUCT_ID
WHERE O.ORDER_ID IS NULL OR P.PRODUCT_ID IS NULL;

-- Expected: zero customers with multiple current dimension records.
SELECT COUNT(*) AS CUSTOMERS_WITH_MULTIPLE_CURRENT_ROWS
FROM (
 SELECT CUSTOMER_ID FROM ANALYTICS.DIM_CUSTOMER WHERE IS_CURRENT=TRUE
 GROUP BY CUSTOMER_ID HAVING COUNT(*)>1
);
