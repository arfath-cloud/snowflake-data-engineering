-- Step 2: Raw landing, audit, dimension and fact tables.
USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_DW;

CREATE TABLE IF NOT EXISTS RAW.CUSTOMERS (
 CUSTOMER_ID NUMBER(10), FIRST_NAME VARCHAR(100), LAST_NAME VARCHAR(100),
 EMAIL VARCHAR(255), CITY VARCHAR(100), STATE VARCHAR(100), COUNTRY VARCHAR(100),
 UPDATED_AT TIMESTAMP_NTZ, SOURCE_FILE VARCHAR(500),
 INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RAW.PRODUCTS (
 PRODUCT_ID NUMBER(10), PRODUCT_NAME VARCHAR(200), CATEGORY VARCHAR(100),
 UNIT_PRICE NUMBER(12,2), ACTIVE_FLAG BOOLEAN, UPDATED_AT TIMESTAMP_NTZ,
 SOURCE_FILE VARCHAR(500), INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RAW.ORDERS (
 ORDER_ID NUMBER(10), CUSTOMER_ID NUMBER(10), ORDER_DATE DATE,
 ORDER_STATUS VARCHAR(30), UPDATED_AT TIMESTAMP_NTZ, SOURCE_FILE VARCHAR(500),
 INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RAW.ORDER_ITEMS (
 ORDER_ITEM_ID NUMBER(10), ORDER_ID NUMBER(10), PRODUCT_ID NUMBER(10),
 QUANTITY NUMBER(10), UNIT_PRICE NUMBER(12,2), UPDATED_AT TIMESTAMP_NTZ,
 SOURCE_FILE VARCHAR(500), INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RAW.CUSTOMER_CHANGES (
 CUSTOMER_ID NUMBER(10), FIRST_NAME VARCHAR(100), LAST_NAME VARCHAR(100),
 EMAIL VARCHAR(255), CITY VARCHAR(100), STATE VARCHAR(100), COUNTRY VARCHAR(100),
 CHANGE_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS CONTROL.INGESTION_AUDIT (
 AUDIT_ID NUMBER AUTOINCREMENT, TABLE_NAME VARCHAR(100), SOURCE_FILE VARCHAR(500),
 ROWS_LOADED NUMBER, LOAD_STATUS VARCHAR(30),
 LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), DETAILS VARCHAR(2000)
);
CREATE TABLE IF NOT EXISTS ANALYTICS.DIM_CUSTOMER (
 CUSTOMER_SK NUMBER AUTOINCREMENT, CUSTOMER_ID NUMBER(10), FIRST_NAME VARCHAR(100),
 LAST_NAME VARCHAR(100), EMAIL VARCHAR(255), CITY VARCHAR(100), STATE VARCHAR(100),
 COUNTRY VARCHAR(100), EFFECTIVE_FROM TIMESTAMP_NTZ, EFFECTIVE_TO TIMESTAMP_NTZ,
 IS_CURRENT BOOLEAN, RECORD_HASH VARCHAR(64)
);
CREATE TABLE IF NOT EXISTS ANALYTICS.DIM_PRODUCT (
 PRODUCT_ID NUMBER(10), PRODUCT_NAME VARCHAR(200), CATEGORY VARCHAR(100),
 UNIT_PRICE NUMBER(12,2), ACTIVE_FLAG BOOLEAN
);
CREATE TABLE IF NOT EXISTS ANALYTICS.FACT_ORDER (
 ORDER_ID NUMBER(10), CUSTOMER_ID NUMBER(10), ORDER_DATE DATE,
 ORDER_STATUS VARCHAR(30), ORDER_TOTAL NUMBER(14,2),
 LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
