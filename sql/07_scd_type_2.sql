-- Step 7: SCD Type 2. Assumes staging view exists and source UPDATED_AT is newer.
USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_DW;

-- Close changed current versions.
UPDATE ANALYTICS.DIM_CUSTOMER D
SET EFFECTIVE_TO=S.UPDATED_AT,IS_CURRENT=FALSE
FROM STAGING.V_CUSTOMERS S
WHERE D.CUSTOMER_ID=S.CUSTOMER_ID AND D.IS_CURRENT=TRUE
 AND D.RECORD_HASH<>SHA2(CONCAT_WS('|',S.FIRST_NAME,S.LAST_NAME,S.EMAIL,S.CITY,S.STATE,S.COUNTRY),256)
 AND S.UPDATED_AT>D.EFFECTIVE_FROM;

-- Insert a new current version when no current version exists.
INSERT INTO ANALYTICS.DIM_CUSTOMER
 (CUSTOMER_ID,FIRST_NAME,LAST_NAME,EMAIL,CITY,STATE,COUNTRY,EFFECTIVE_FROM,EFFECTIVE_TO,IS_CURRENT,RECORD_HASH)
SELECT S.CUSTOMER_ID,S.FIRST_NAME,S.LAST_NAME,S.EMAIL,S.CITY,S.STATE,S.COUNTRY,
 S.UPDATED_AT,'9999-12-31'::TIMESTAMP_NTZ,TRUE,
 SHA2(CONCAT_WS('|',S.FIRST_NAME,S.LAST_NAME,S.EMAIL,S.CITY,S.STATE,S.COUNTRY),256)
FROM STAGING.V_CUSTOMERS S
LEFT JOIN ANALYTICS.DIM_CUSTOMER D
 ON D.CUSTOMER_ID=S.CUSTOMER_ID AND D.IS_CURRENT=TRUE
WHERE D.CUSTOMER_ID IS NULL;

SELECT CUSTOMER_ID,CITY,STATE,EFFECTIVE_FROM,EFFECTIVE_TO,IS_CURRENT
FROM ANALYTICS.DIM_CUSTOMER ORDER BY CUSTOMER_ID,EFFECTIVE_FROM;
