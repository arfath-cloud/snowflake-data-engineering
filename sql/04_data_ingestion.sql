-- Step 4: Upload the four CSV files to @RETAIL_DW.RAW.RETAIL_RAW_STAGE first.
USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_DW;

COPY INTO RAW.CUSTOMERS
 (CUSTOMER_ID,FIRST_NAME,LAST_NAME,EMAIL,CITY,STATE,COUNTRY,UPDATED_AT,SOURCE_FILE)
FROM (SELECT $1::NUMBER,$2::VARCHAR,$3::VARCHAR,$4::VARCHAR,$5::VARCHAR,$6::VARCHAR,
 $7::VARCHAR,$8::TIMESTAMP_NTZ,METADATA$FILENAME
 FROM @RAW.RETAIL_RAW_STAGE)
FILES=('customers.csv') FILE_FORMAT=(FORMAT_NAME=RAW.RETAIL_CSV_FORMAT)
ON_ERROR='ABORT_STATEMENT';

COPY INTO RAW.PRODUCTS
 (PRODUCT_ID,PRODUCT_NAME,CATEGORY,UNIT_PRICE,ACTIVE_FLAG,UPDATED_AT,SOURCE_FILE)
FROM (SELECT $1::NUMBER,$2::VARCHAR,$3::VARCHAR,$4::NUMBER(12,2),$5::BOOLEAN,
 $6::TIMESTAMP_NTZ,METADATA$FILENAME FROM @RAW.RETAIL_RAW_STAGE)
FILES=('products.csv') FILE_FORMAT=(FORMAT_NAME=RAW.RETAIL_CSV_FORMAT)
ON_ERROR='ABORT_STATEMENT';

COPY INTO RAW.ORDERS
 (ORDER_ID,CUSTOMER_ID,ORDER_DATE,ORDER_STATUS,UPDATED_AT,SOURCE_FILE)
FROM (SELECT $1::NUMBER,$2::NUMBER,$3::DATE,$4::VARCHAR,$5::TIMESTAMP_NTZ,
 METADATA$FILENAME FROM @RAW.RETAIL_RAW_STAGE)
FILES=('orders.csv') FILE_FORMAT=(FORMAT_NAME=RAW.RETAIL_CSV_FORMAT)
ON_ERROR='ABORT_STATEMENT';

COPY INTO RAW.ORDER_ITEMS
 (ORDER_ITEM_ID,ORDER_ID,PRODUCT_ID,QUANTITY,UNIT_PRICE,UPDATED_AT,SOURCE_FILE)
FROM (SELECT $1::NUMBER,$2::NUMBER,$3::NUMBER,$4::NUMBER,$5::NUMBER(12,2),
 $6::TIMESTAMP_NTZ,METADATA$FILENAME FROM @RAW.RETAIL_RAW_STAGE)
FILES=('order_items.csv') FILE_FORMAT=(FORMAT_NAME=RAW.RETAIL_CSV_FORMAT)
ON_ERROR='ABORT_STATEMENT';

SELECT 'CUSTOMERS' TABLE_NAME,COUNT(*) ROW_COUNT FROM RAW.CUSTOMERS
UNION ALL SELECT 'PRODUCTS',COUNT(*) FROM RAW.PRODUCTS
UNION ALL SELECT 'ORDERS',COUNT(*) FROM RAW.ORDERS
UNION ALL SELECT 'ORDER_ITEMS',COUNT(*) FROM RAW.ORDER_ITEMS;
