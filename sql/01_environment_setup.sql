-- Step 1: Environment setup. Requires privileges to create warehouse/database.
CREATE WAREHOUSE IF NOT EXISTS RETAIL_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Small warehouse for Snowflake portfolio learning';

CREATE DATABASE IF NOT EXISTS RETAIL_DW
  COMMENT = 'Synthetic retail data engineering project';
CREATE SCHEMA IF NOT EXISTS RETAIL_DW.RAW;
CREATE SCHEMA IF NOT EXISTS RETAIL_DW.STAGING;
CREATE SCHEMA IF NOT EXISTS RETAIL_DW.ANALYTICS;
CREATE SCHEMA IF NOT EXISTS RETAIL_DW.CONTROL;

USE WAREHOUSE RETAIL_WH;
SHOW SCHEMAS IN DATABASE RETAIL_DW;
SHOW WAREHOUSES LIKE 'RETAIL_WH';

