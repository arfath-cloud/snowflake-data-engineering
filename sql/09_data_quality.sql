-- Step 9: Data quality checks. Empty result sets indicate checks passed.
USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_DW;

-- Null business keys.
SELECT 'CUSTOMERS' TABLE_NAME,COUNT_IF(CUSTOMER_ID IS NULL) NULL_KEY_COUNT FROM RAW.CUSTOMERS
UNION ALL SELECT 'PRODUCTS',COUNT_IF(PRODUCT_ID IS NULL) FROM RAW.PRODUCTS
UNION ALL SELECT 'ORDERS',COUNT_IF(ORDER_ID IS NULL) FROM RAW.ORDERS;

-- Duplicate customer keys in raw.
SELECT CUSTOMER_ID,COUNT(*) ROW_COUNT FROM RAW.CUSTOMERS
GROUP BY CUSTOMER_ID HAVING COUNT(*)>1;

-- Orders with no customer.
SELECT O.ORDER_ID,O.CUSTOMER_ID FROM STAGING.V_ORDERS O
LEFT JOIN STAGING.V_CUSTOMERS C ON O.CUSTOMER_ID=C.CUSTOMER_ID
WHERE C.CUSTOMER_ID IS NULL;

-- Invalid order items.
SELECT * FROM RAW.ORDER_ITEMS WHERE QUANTITY<=0 OR UNIT_PRICE<0;

-- More than one current SCD2 row per customer.
SELECT CUSTOMER_ID,COUNT(*) CURRENT_ROW_COUNT
FROM ANALYTICS.DIM_CUSTOMER WHERE IS_CURRENT=TRUE
GROUP BY CUSTOMER_ID HAVING COUNT(*)>1;
