-- Step 8: Stream and task demonstration.
-- First create stream and procedure. Task remains suspended until explicitly resumed.
USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_DW;

CREATE STREAM IF NOT EXISTS RAW.CUSTOMER_CHANGES_STREAM
 ON TABLE RAW.CUSTOMER_CHANGES APPEND_ONLY=FALSE SHOW_INITIAL_ROWS=FALSE;

-- This procedure consumes INSERT events from the stream and merges current records.
-- For a learning demo, test a single change at a time and inspect results.
CREATE OR REPLACE PROCEDURE CONTROL.APPLY_CUSTOMER_CHANGES()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
  MERGE INTO ANALYTICS.DIM_CUSTOMER T
  USING (
    SELECT CUSTOMER_ID,FIRST_NAME,LAST_NAME,EMAIL,CITY,STATE,COUNTRY,CHANGE_TS,
      SHA2(CONCAT_WS('|',FIRST_NAME,LAST_NAME,EMAIL,CITY,STATE,COUNTRY),256) RECORD_HASH
    FROM RAW.CUSTOMER_CHANGES_STREAM
    WHERE METADATA$ACTION='INSERT'
    QUALIFY ROW_NUMBER() OVER(PARTITION BY CUSTOMER_ID ORDER BY CHANGE_TS DESC)=1
  ) S
  ON T.CUSTOMER_ID=S.CUSTOMER_ID AND T.IS_CURRENT=TRUE
  WHEN MATCHED AND T.RECORD_HASH<>S.RECORD_HASH
    THEN UPDATE SET EFFECTIVE_TO=S.CHANGE_TS,IS_CURRENT=FALSE;

  INSERT INTO ANALYTICS.DIM_CUSTOMER
   (CUSTOMER_ID,FIRST_NAME,LAST_NAME,EMAIL,CITY,STATE,COUNTRY,
    EFFECTIVE_FROM,EFFECTIVE_TO,IS_CURRENT,RECORD_HASH)
  SELECT S.CUSTOMER_ID,S.FIRST_NAME,S.LAST_NAME,S.EMAIL,S.CITY,S.STATE,S.COUNTRY,
    S.CHANGE_TS,'9999-12-31'::TIMESTAMP_NTZ,TRUE,S.RECORD_HASH
  FROM (
    SELECT CUSTOMER_ID,FIRST_NAME,LAST_NAME,EMAIL,CITY,STATE,COUNTRY,CHANGE_TS,
      SHA2(CONCAT_WS('|',FIRST_NAME,LAST_NAME,EMAIL,CITY,STATE,COUNTRY),256) RECORD_HASH
    FROM RAW.CUSTOMER_CHANGES_STREAM
    WHERE METADATA$ACTION='INSERT'
    QUALIFY ROW_NUMBER() OVER(PARTITION BY CUSTOMER_ID ORDER BY CHANGE_TS DESC)=1
  ) S
  WHERE NOT EXISTS (
    SELECT 1 FROM ANALYTICS.DIM_CUSTOMER D
    WHERE D.CUSTOMER_ID=S.CUSTOMER_ID AND D.IS_CURRENT=TRUE
  );

  RETURN 'Stream change batch processed';
END;
$$;

CREATE TASK IF NOT EXISTS CONTROL.CUSTOMER_CHANGE_TASK
 WAREHOUSE=RETAIL_WH SCHEDULE='5 MINUTE'
 WHEN SYSTEM$STREAM_HAS_DATA('RETAIL_DW.RAW.CUSTOMER_CHANGES_STREAM')
AS CALL CONTROL.APPLY_CUSTOMER_CHANGES();

