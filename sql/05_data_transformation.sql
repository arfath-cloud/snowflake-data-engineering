-- Step 5: Staging views and initial analytics loads.
USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_DW;

CREATE OR REPLACE VIEW STAGING.V_CUSTOMERS AS
SELECT CUSTOMER_ID,TRIM(FIRST_NAME) FIRST_NAME,TRIM(LAST_NAME) LAST_NAME,
 LOWER(TRIM(EMAIL)) EMAIL,TRIM(CITY) CITY,TRIM(STATE) STATE,TRIM(COUNTRY) COUNTRY,
 UPDATED_AT
FROM RAW.CUSTOMERS
QUALIFY ROW_NUMBER() OVER(PARTITION BY CUSTOMER_ID ORDER BY UPDATED_AT DESC,INGESTED_AT DESC)=1;

CREATE OR REPLACE VIEW STAGING.V_PRODUCTS AS
SELECT PRODUCT_ID,TRIM(PRODUCT_NAME) PRODUCT_NAME,TRIM(CATEGORY) CATEGORY,
 UNIT_PRICE,ACTIVE_FLAG,UPDATED_AT
FROM RAW.PRODUCTS
QUALIFY ROW_NUMBER() OVER(PARTITION BY PRODUCT_ID ORDER BY UPDATED_AT DESC,INGESTED_AT DESC)=1;

CREATE OR REPLACE VIEW STAGING.V_ORDERS AS
SELECT ORDER_ID,CUSTOMER_ID,ORDER_DATE,UPPER(TRIM(ORDER_STATUS)) ORDER_STATUS,UPDATED_AT
FROM RAW.ORDERS
QUALIFY ROW_NUMBER() OVER(PARTITION BY ORDER_ID ORDER BY UPDATED_AT DESC,INGESTED_AT DESC)=1;

CREATE OR REPLACE VIEW STAGING.V_ORDER_ITEMS AS
SELECT ORDER_ITEM_ID,ORDER_ID,PRODUCT_ID,QUANTITY,UNIT_PRICE,UPDATED_AT
FROM RAW.ORDER_ITEMS
QUALIFY ROW_NUMBER() OVER(PARTITION BY ORDER_ITEM_ID ORDER BY UPDATED_AT DESC,INGESTED_AT DESC)=1;

INSERT INTO ANALYTICS.DIM_CUSTOMER
 (CUSTOMER_ID,FIRST_NAME,LAST_NAME,EMAIL,CITY,STATE,COUNTRY,EFFECTIVE_FROM,EFFECTIVE_TO,IS_CURRENT,RECORD_HASH)
SELECT C.CUSTOMER_ID,C.FIRST_NAME,C.LAST_NAME,C.EMAIL,C.CITY,C.STATE,C.COUNTRY,
 COALESCE(C.UPDATED_AT,CURRENT_TIMESTAMP()),'9999-12-31'::TIMESTAMP_NTZ,TRUE,
 SHA2(CONCAT_WS('|',C.FIRST_NAME,C.LAST_NAME,C.EMAIL,C.CITY,C.STATE,C.COUNTRY),256)
FROM STAGING.V_CUSTOMERS C
WHERE NOT EXISTS(SELECT 1 FROM ANALYTICS.DIM_CUSTOMER D
 WHERE D.CUSTOMER_ID=C.CUSTOMER_ID AND D.IS_CURRENT=TRUE);

MERGE INTO ANALYTICS.DIM_PRODUCT T USING STAGING.V_PRODUCTS S
ON T.PRODUCT_ID=S.PRODUCT_ID
WHEN MATCHED THEN UPDATE SET PRODUCT_NAME=S.PRODUCT_NAME,CATEGORY=S.CATEGORY,
 UNIT_PRICE=S.UNIT_PRICE,ACTIVE_FLAG=S.ACTIVE_FLAG
WHEN NOT MATCHED THEN INSERT(PRODUCT_ID,PRODUCT_NAME,CATEGORY,UNIT_PRICE,ACTIVE_FLAG)
 VALUES(S.PRODUCT_ID,S.PRODUCT_NAME,S.CATEGORY,S.UNIT_PRICE,S.ACTIVE_FLAG);

MERGE INTO ANALYTICS.FACT_ORDER T USING (
 SELECT O.ORDER_ID,O.CUSTOMER_ID,O.ORDER_DATE,O.ORDER_STATUS,
  SUM(I.QUANTITY*I.UNIT_PRICE) ORDER_TOTAL
 FROM STAGING.V_ORDERS O LEFT JOIN STAGING.V_ORDER_ITEMS I ON O.ORDER_ID=I.ORDER_ID
 GROUP BY O.ORDER_ID,O.CUSTOMER_ID,O.ORDER_DATE,O.ORDER_STATUS
) S ON T.ORDER_ID=S.ORDER_ID
WHEN MATCHED THEN UPDATE SET CUSTOMER_ID=S.CUSTOMER_ID,ORDER_DATE=S.ORDER_DATE,
 ORDER_STATUS=S.ORDER_STATUS,ORDER_TOTAL=S.ORDER_TOTAL
WHEN NOT MATCHED THEN INSERT(ORDER_ID,CUSTOMER_ID,ORDER_DATE,ORDER_STATUS,ORDER_TOTAL)
 VALUES(S.ORDER_ID,S.CUSTOMER_ID,S.ORDER_DATE,S.ORDER_STATUS,S.ORDER_TOTAL);

SELECT * FROM ANALYTICS.FACT_ORDER ORDER BY ORDER_ID;
