-- Step 3: CSV file format and internal stage.
USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_DW;
CREATE FILE FORMAT IF NOT EXISTS RAW.RETAIL_CSV_FORMAT
 TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1
 FIELD_OPTIONALLY_ENCLOSED_BY = '"' EMPTY_FIELD_AS_NULL = TRUE
 NULL_IF = ('NULL','null');
CREATE STAGE IF NOT EXISTS RAW.RETAIL_RAW_STAGE
 FILE_FORMAT = RAW.RETAIL_CSV_FORMAT
 COMMENT = 'Internal stage for synthetic retail CSV files';
-- Upload the four CSVs through Snowsight, then:
LIST @RAW.RETAIL_RAW_STAGE;
